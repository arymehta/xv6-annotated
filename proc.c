// Set up first user process.
void
userinit(void)
{
  struct proc *p;
  extern char _binary_initcode_start[], _binary_initcode_size[];

  p = allocproc();

  initproc = p;
  if((p->pgdir = setupkvm()) == 0)
    panic("userinit: out of memory?");
  inituvm(p->pgdir, _binary_initcode_start, (int)_binary_initcode_size);
  p->sz = PGSIZE;
  memset(p->tf, 0, sizeof(*p->tf));
  p->tf->cs = (SEG_UCODE << 3) | DPL_USER;
  p->tf->ds = (SEG_UDATA << 3) | DPL_USER;
  p->tf->es = p->tf->ds;
  p->tf->ss = p->tf->ds;
  p->tf->eflags = FL_IF;
  p->tf->esp = PGSIZE;
  p->tf->eip = 0;  // beginning of initcode.S

  safestrcpy(p->name, "initcode", sizeof(p->name));
  p->cwd = namei("/");

  // this assignment to p->state lets other cores
  // run this process. the acquire forces the above
  // writes to be visible, and the lock is also needed
  // because the assignment might not be atomic.
  acquire(&ptable.lock);

  p->state = RUNNABLE;

  release(&ptable.lock);
}

// Grow current process's memory by n bytes.
// Return 0 on success, -1 on failure.
int
growproc(int n)
{
  uint sz;
  struct proc *curproc = myproc();

  sz = curproc->sz;
  if(n > 0){
    if((sz = allocuvm(curproc->pgdir, sz, sz + n)) == 0)
      return -1;
  } else if(n < 0){
    if((sz = deallocuvm(curproc->pgdir, sz, sz + n)) == 0)
      return -1;
  }
  curproc->sz = sz;
  switchuvm(curproc);
  return 0;
}

// Create a new process copying p as the parent.
// Sets up stack to return as if from system call.
// Caller must set state of returned proc to RUNNABLE.
int
fork(void)
{
  int i, pid;
  struct proc *np;
  struct proc *curproc = myproc();

  // Allocate process.
  if((np = allocproc()) == 0){
    return -1;
  }

  // Copy process state from proc.
  if((np->pgdir = copyuvm(curproc->pgdir, curproc->sz)) == 0){
    kfree(np->kstack);
    np->kstack = 0;
    np->state = UNUSED;
    return -1;
  }
  np->sz = curproc->sz;
  np->parent = curproc;
  *np->tf = *curproc->tf;

  // Clear %eax so that fork returns 0 in the child.
  np->tf->eax = 0;

  for(i = 0; i < NOFILE; i++)
    if(curproc->ofile[i])
      np->ofile[i] = filedup(curproc->ofile[i]);
  np->cwd = idup(curproc->cwd);

  safestrcpy(np->name, curproc->name, sizeof(curproc->name));

  pid = np->pid;

  acquire(&ptable.lock);

  np->state = RUNNABLE;

  release(&ptable.lock);

  return pid;
}

// Exit the current process.  Does not return.
// An exited process remains in the zombie state
// until its parent calls wait() to find out it exited.
void
exit(void)
{
  struct proc *curproc = myproc();
  struct proc *p;
  int fd;

  if(curproc == initproc)
    panic("init exiting");

  // Close all open files.
  for(fd = 0; fd < NOFILE; fd++){
    if(curproc->ofile[fd]){
      fileclose(curproc->ofile[fd]);
      curproc->ofile[fd] = 0;
    }
  }

  begin_op();
  iput(curproc->cwd);
  end_op();
  curproc->cwd = 0;

  acquire(&ptable.lock);

  // Parent might be sleeping in wait().
  wakeup1(curproc->parent);

  // Pass abandoned children to init.
  for(p = ptable.proc; p < &ptable.proc[NPROC]; p++){
    if(p->parent == curproc){
      p->parent = initproc;
      if(p->state == ZOMBIE)
        wakeup1(initproc);
    }
  }

  // Jump into the scheduler, never to return.
  curproc->state = ZOMBIE;
  sched();
  panic("zombie exit");
}

// Wait for a child process to exit and return its pid.
// Return -1 if this process has no children.
int
wait(void)
{
  struct proc *p;
  int havekids, pid;
  struct proc *curproc = myproc();

  acquire(&ptable.lock);
  for(;;){
    // Scan through table looking for exited children.
    havekids = 0;
    for(p = ptable.proc; p < &ptable.proc[NPROC]; p++){
      if(p->parent != curproc)
        continue;
      havekids = 1;
      if(p->state == ZOMBIE){
        // Found one.
        pid = p->pid;
        kfree(p->kstack);
        p->kstack = 0;
        freevm(p->pgdir);
        p->pid = 0;
        p->parent = 0;
        p->name[0] = 0;
        p->killed = 0;
        p->state = UNUSED;
        release(&ptable.lock);
        return pid;
      }
    }

    // No point waiting if we don't have any children.
    if(!havekids || curproc->killed){
      release(&ptable.lock);
      return -1;
    }

    // Wait for children to exit.  (See wakeup1 call in proc_exit.)
    sleep(curproc, &ptable.lock);  //DOC: wait-sleep
  }
}

//PAGEBREAK: 42
// Per-CPU process scheduler.
// Each CPU calls scheduler() after setting itself up.
// Scheduler never returns.  It loops, doing:
//  - choose a process to run
//  - swtch to start running that process
//  - eventually that process transfers control
//      via swtch back to the scheduler.

/*
 * ARYAN:
 *      - switches to P2 from scheduler
 *      - steps involved:
 *          -> setting up TSS (so that cpu knows where kstack of new process lies)
 *          -> saving current scheduler state
 *          -> switch to stack of new process
 *          -> return into the kstack of that process
 *
 *          NOTE: context switch:
 *          - scheduler is called only once *directly* to schedule the INIT process
 *          - otherwise its always callled through sched()
 *          - sched() -- switches from P1 to scheduler code
 *          - scheduler() -- picks P2, and switches to that
 *          - both functions use swtch.S
 *
 *
 *          STEP BY STEP:
 *          1) P1 is running
 *          2) timer interrupt
 *          3) IDT -> change mode from user to kernel -> change ss, esp P1 kstack(from TSS) -> vectors.S ->
 *          alltraps(sets up trapframe) -> trap()
 *          4) trap() -> TIMERINTR -> yeild()
 *          5) yeild() -> swtch(&(p1->context), cpu->sheduler) == switches executing stack from P1 kstack to scheduler
 *              -> scheduler()
 *          6) scheduler() selects a process using round robin -> sets up TSS for P2 (switchuvm())
 *              -> swtch(&(cpu->scheduler), p2->context) == switches to kstack of P2
 *          7) swtch.
 *          ret --> pops the EIP --> which was automatically saved by the hardware, FROM P2 kstack
 *          --> means jumps directly into P2 kstack
 *
 *          8) So in this process, in swtch(), P1's context got appropriately saved in P1 kstack, and succesfully jumped to P2
 *
 *
*/
void
scheduler(void)
{
  struct proc *p;
  struct cpu *c = mycpu();
  c->proc = 0;

  for(;;){
    // Enable interrupts on this processor.
    sti();

    // Loop over process table looking for process to run.
    acquire(&ptable.lock);
    for(p = ptable.proc; p < &ptable.proc[NPROC]; p++){
      if(p->state != RUNNABLE)
        continue;

      // Switch to chosen process.  It is the process's job
      // to release ptable.lock and then reacquire it
      // before jumping back to us.


      c->proc = p;
      switchuvm(p); // ARYAN: setting up TSS of current CPU to kstack of P2
      p->state = RUNNING;

      swtch(&(c->scheduler), p->context); // ARYAN: switches from scheduler to kstack of P2


      switchkvm();

      // Process is done running for now.
      // It should have changed its p->state before coming back.
      c->proc = 0;
    }
    release(&ptable.lock);

  }
}

/* ARYAN
 * Q) Why is TSS even needed? Dont we already have proc->kstack to tell us where kstack is?
 * Ans) User mode process -> interrupt -> neeeds kstack immediately to push and create trapframe
 * -> BUT struct proc is in kernel space, cannot access from user mode
 * -> this is why the value is stored before hand while P1 was BEING scheduled(while it was still in kernel mode).
 * */


// Enter scheduler.  Must hold only ptable.lock
// and have changed proc->state. Saves and restores
// intena because intena is a property of this
// kernel thread, not this CPU. It should
// be proc->intena and proc->ncli, but that would
// break in the few places where a lock is held but
// there's no process.
void
sched(void)
{
  int intena;
  struct proc *p = myproc();

  if(!holding(&ptable.lock)) // Aryan: sched() expects ptable to be held
    panic("sched ptable.lock");
  if(mycpu()->ncli != 1) // Aryan: The calling process should hold only 1 spinlock
    panic("sched locks");
  if(p->state == RUNNING)
    panic("sched running");
  if(readeflags()&FL_IF)
    panic("sched interruptible");
  intena = mycpu()->intena;
    // Aryan: switches from P1 kstack to scheduler (no need to setup TSS because it was already setup when P1 got scheduled)
  swtch(&p->context, mycpu()->scheduler);
  mycpu()->intena = intena;
}

// Give up the CPU for one scheduling round.
void
yield(void)
{
  acquire(&ptable.lock);  //DOC: yieldlock
  myproc()->state = RUNNABLE;
  sched();
  release(&ptable.lock); // !!! -- Release "spinlock"
}
/* Aryan: JOURNEY of ptable.lock:
 * - Notice that in sleep(), we block the process WHILE holdding the ptable spinlock
 * - Actually violates the rule, this is a special case because:
 *
 * 1) sleep() -> acquires ptable lock, calls sched()
 * 2) sched() -> calls swtch -> switches to processor kstack -> scheduler()
 * 3) Here, WHILE ptable is still held, scheduler() -> selects a new process and call swtch()
 * 4) swtch() -> shed -> switches to P2 kstack
 * 5) Suppose P2 was blocked because of timer interrupt, means it called yield()
 * 6) after it returns, from sched(), the line RIGHT after sched is...
 * release(&ptable.lock)! :)
 *
 * Basically, the ptable lock acquired from one process P1 is then released after context switch
 * by another process P2!
 *
 * Note: For init process when CPU starts in scheduler(), acquire lock is already called BEFORE infinite loop
 * So ensures that the ptable lock is always acquired in scheduler()
 */

// A fork child's very first scheduling by scheduler()
// will swtch here.  "Return" to user space.
void
forkret(void)
{
  static int first = 1;
  // Still holding ptable.lock from scheduler.
  release(&ptable.lock);

  if (first) {
    // Some initialization functions must be run in the context
    // of a regular process (e.g., they call sleep), and thus cannot
    // be run from main().
    first = 0;
    iinit(ROOTDEV);
    initlog(ROOTDEV);
  }

  // Return to "caller", actually trapret (see allocproc).
}

// Atomically release lock and sleep on chan.
// Reacquires lock when awakened.

/* Aryan:
 * NOTE: this code actually breaks a v imp rule
 * "Never block when holding a spinlock"
 * Here, we acquire the ptable lock -- then we call sched()
*/
void
sleep(void *chan, struct spinlock *lk)
{
  struct proc *p = myproc();

  if(p == 0)
    panic("sleep");

  if(lk == 0)
    panic("sleep without lk");

  // Must acquire ptable.lock in order to
  // change p->state and then call sched.
  // Once we hold ptable.lock, we can be
  // guaranteed that we won't miss any wakeup
  // (wakeup runs with ptable.lock locked),
  // so it's okay to release lk.
  if(lk != &ptable.lock){  //DOC: sleeplock0
    acquire(&ptable.lock);  //DOC: sleeplock1
    release(lk); // Aryan: Sleep always releases the lock before blocking -- otherwise other process will have to wait for this one to wakeup
  }
  // Go to sleep.
  p->chan = chan;
  p->state = SLEEPING; // blocks while holding a sleeplock!

  sched();

  // Tidy up.
  p->chan = 0;

  // Reacquire original lock.
  if(lk != &ptable.lock){  //DOC: sleeplock2
    release(&ptable.lock);
    acquire(lk);
  }
}

//PAGEBREAK!
// Wake up all processes sleeping on chan.
// The ptable lock must be held.
static void
wakeup1(void *chan)
{
    // expects the calling function to have acquired the lock
  struct proc *p;

  // Iterates over the ptable, find the sleeping process that is blocked on that chan
  // and makes it runnable(wakes it up)
  for(p = ptable.proc; p < &ptable.proc[NPROC]; p++)
    if(p->state == SLEEPING && p->chan == chan)
      p->state = RUNNABLE;
}

// Wake up all processes sleeping on chan.
void
wakeup(void *chan)
{
  acquire(&ptable.lock);
  wakeup1(chan);
  release(&ptable.lock);
}

// Kill the process with the given pid.
// Process won't exit until it returns
// to user space (see trap in trap.c).
int
kill(int pid)
{
  struct proc *p;

  acquire(&ptable.lock);
  for(p = ptable.proc; p < &ptable.proc[NPROC]; p++){
    if(p->pid == pid){
      p->killed = 1;
      // Wake process from sleep if necessary.
      if(p->state == SLEEPING)
        p->state = RUNNABLE;
      release(&ptable.lock);
      return 0;
    }
  }
  release(&ptable.lock);
  return -1;
}

